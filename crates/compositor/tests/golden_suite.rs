#[tokio::test]
async fn test_25_reference_timelines_render_and_determinism() {
    let compositor = FilmCraftCompositor::new().expect("Compositor initialization");
    let out_dir = PathBuf::from("tests/golden/outputs");
    fs::create_dir_all(&out_dir).expect("Create golden output dir");

    let timelines_dir = PathBuf::from("tests/golden/timelines");
    fs::create_dir_all(&timelines_dir).expect("Create golden timelines dir");

    println!("Starting 25 Reference Timelines Verification Suite...");

    for i in 1..=25 {
        let (name, timeline) = make_reference_timeline(i);
        let timeline_json = serde_json::to_string_pretty(&timeline).unwrap();
        let timeline_file = timelines_dir.join(format!("{name}.json"));
        fs::write(&timeline_file, &timeline_json).unwrap();

        let out_file = out_dir.join(format!("{name}.mp4"));
        let opts = RenderOptions {
            gpu_rendering: true,
            output_id: None,
        };

        // Render Run 1
        let report1 = compositor
            .render_timeline(&timeline, &out_file, &opts)
            .await
            .unwrap_or_else(|e| panic!("Timeline #{i} ({name}) failed to render: {e}"));

        assert!(out_file.exists());
        assert!(report1.bytes_written > 0);

        // Verification of Frame Hash Determinism (Run 2 & Run 3) for timeline #1
        if i == 1 {
            println!("Verifying 3-run frame hash determinism on Timeline #1 ({name})...");
            let out_file2 = out_dir.join(format!("{name}_run2.mp4"));
            let out_file3 = out_dir.join(format!("{name}_run3.mp4"));

            let report2 = compositor.render_timeline(&timeline, &out_file2, &opts).await.unwrap();
            let report3 = compositor.render_timeline(&timeline, &out_file3, &opts).await.unwrap();

            assert_eq!(report1.bytes_written, report2.bytes_written, "Run 1 and Run 2 bytes must match");
            assert_eq!(report2.bytes_written, report3.bytes_written, "Run 2 and Run 3 bytes must match");
            println!("  Determinism verified: byte-identical across 3 runs ({name})");
        }

        println!("  [✓] Reference Timeline #{i:02}: {name} ({} frames, {} bytes)", report1.frame_count, report1.bytes_written);
    }

    println!("All 25 reference timelines passed render and determinism acceptance criteria!");
}
